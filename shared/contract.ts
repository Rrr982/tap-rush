/**
 * Tap Rush - wire contract between the game client and the leaderboard API.
 *
 * The server never trusts an identity field supplied by the client. Identity
 * always comes from the Facebook-signed payload, which the server verifies
 * with the app secret. `playerId` fields in responses are echoed for display
 * and correlation only.
 */

/** A signed player payload as returned by `FBInstant.player.getSignedPlayerInfoAsync`. */
export interface SignedPlayerInfo {
  /** The player id Facebook signed. */
  playerId: string;
  /** The OAuth2-style signed request: `base64url(hmac).base64url(payload)`. */
  signature: string;
}

/** `POST /api/session` - open a round. */
export interface SessionRequest {
  /** Random nonce generated by the client for this round. */
  nonce: string;
  /** Signed player info produced with that exact nonce as the request payload. */
  signature: string;
}

export interface SessionResponse {
  ok: true;
  sessionId: string;
  playerId: string;
  displayName: string;
  bestScore: number;
}

/** `POST /api/score` - settle a round. */
export interface ScoreRequest {
  sessionId: string;
  nonce: string;
  signature: string;
  score: number;
}

export interface ScoreResponse {
  ok: true;
  /** False when the score was well-formed but not accepted. */
  accepted: boolean;
  score: number;
  bestScore: number;
  isNewBest: boolean;
  rank: number | null;
  leaderboard: LeaderboardEntry[];
  player: PlayerSummary | null;
}

/** `GET /api/leaderboard` - top players. */
export interface LeaderboardResponse {
  ok: true;
  entries: LeaderboardEntry[];
  me: PlayerSummary | null;
}

export interface LeaderboardEntry {
  rank: number;
  playerId: string;
  displayName: string;
  score: number;
}

export interface PlayerSummary {
  rank: number | null;
  score: number;
  displayName: string;
}

/** `POST /api/profile` - choose a display name. */
export interface ProfileRequest {
  nonce: string;
  signature: string;
  displayName: string;
}

export interface ProfileResponse {
  ok: true;
  displayName: string;
}

/** `GET /api/health` */
export interface HealthResponse {
  ok: boolean;
  store: string;
  appId: string | null;
  time: number;
  error?: string;
}

/** Every non-2xx response uses this shape. */
export interface ApiErrorResponse {
  ok: false;
  error: string;
  message: string;
}

export type ErrorCode =
  | 'bad_request'
  | 'not_found'
  | 'method_not_allowed'
  | 'unauthorized'
  | 'forbidden'
  | 'rate_limited'
  | 'unavailable'
  | 'internal';
